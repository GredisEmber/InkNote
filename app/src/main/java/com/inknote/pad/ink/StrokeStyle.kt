package com.inknote.pad.ink

/**
 * 笔迹风格。
 *
 * 三者的关系不是"三选一的三种算法"，而是在压感宽度之上叠不同的修饰：
 *
 *   PRESSURE          宽度 = 基础宽 × 压感系数
 *   PRESSURE_TAPER    再乘一个"离笔画两端越近越细"的系数
 *   PRESSURE_VELOCITY 再乘一个"写得越快越细"的系数
 *
 * 压感永远在，因为它反映的是你的真实运笔力度；B 和 C 只是在此之上做修饰。
 *
 * ============================ 为什么切换是安全的 ============================
 * 每一笔的几何（Stroke.segments）在【收笔时】就烘焙好了，切换风格只影响
 * 之后新写的笔画。所以你可以在一页上先用 A 写一行、切到 B 再写一行，
 * 直接并排对比 —— 不需要反复改代码重编译。
 */
enum class StrokeStyle {
    /** A：纯压感响应。忠实反映运笔力度，不做任何额外修饰 */
    PRESSURE,

    /** B：压感 + 起笔收笔渐细。视觉冲击最强，像毛笔/书法 */
    PRESSURE_TAPER,

    /** C：压感 + 速度调制。写得快处自动变细，像真实钢笔在纸上的拖拽感 */
    PRESSURE_VELOCITY,
}
